"""
Tiny i18n layer for the bot (English / Português / Español).

The preference lives on the Aero Platform (``lang_prefs`` table) so it
survives restarts and is shared with the dashboard. ``t(discord_id, key)``
is the normal entry point: it looks the user's language up (cached) and
returns the translated string. Unknown keys fall back to English and then
to the key itself, so a missing translation never breaks a command.
"""
from __future__ import annotations

import logging
import time

import platform_bridge as db

log = logging.getLogger("keybot.i18n")

LANGS = ("en", "pt", "es")
LANG_NAMES = {"en": "English", "pt": "Português", "es": "Español"}
LANG_FLAGS = {"en": "🇺🇸", "pt": "🇧🇷", "es": "🇪🇸"}

# discord_id -> (lang, fetched_at). A short TTL means a change made from the
# dashboard reaches the bot without a restart, while normal traffic stays
# cache-only (no HTTP per message).
_CACHE_TTL = 300
_cache: dict[int, tuple[str, float]] = {}


def get_lang(discord_id: int | None) -> str:
    """The user's language, defaulting to English."""
    if discord_id is None:
        return "en"
    uid = int(discord_id)
    cached = _cache.get(uid)
    if cached and time.time() - cached[1] < _CACHE_TTL:
        return cached[0]
    try:
        lang = db.lang_get(uid)
    except Exception:
        log.exception("lang_get failed; using English")
        lang = "en"
    if lang not in LANGS:
        lang = "en"
    _cache[uid] = (lang, time.time())
    return lang


def set_lang(discord_id: int, lang: str) -> str:
    """Persists the choice and refreshes the cache."""
    lang = (lang or "").strip().lower()
    if lang not in LANGS:
        raise ValueError("lang must be en, pt or es")
    saved = db.lang_set(int(discord_id), lang)
    _cache[int(discord_id)] = (saved, time.time())
    return saved


def t(discord_id: int | None, key: str, **kwargs) -> str:
    """Translates ``key`` for this user (English fallback)."""
    lang = get_lang(discord_id)
    text = TEXTS.get(lang, {}).get(key)
    if text is None:
        text = TEXTS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def tl(lang: str, key: str, **kwargs) -> str:
    """Translates by language code (for menus built for a whole guild)."""
    if lang not in TEXTS:
        lang = "en"
    text = TEXTS[lang].get(key) or TEXTS["en"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


